#!/usr/bin/env node
// Renders every style for both demo sets and writes the static preview site into site/.
// Usage: node scripts/build-gallery.mjs [--style ID[,ID]] [--locale L[,L]] [--skip-render]
// Env: SITE_BASE  public base path of the site (default "/site/" for render/serve.mjs), e.g. "/shot-butcher/"
//      SHOTS_URL  where the shot images are served from (default "<SITE_BASE>shots/")
//      SITE_URL   absolute origin for canonical/OG tags (default "https://graphicmeat.com")
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import sharp from 'sharp';
import { startRenderer } from '../render/render.mjs';
import { ROOT } from '../render/serve.mjs';
import { STYLE_IDS, loadStyle } from '../engine/styles/index.js';
import { toPrompt, resolveSet } from '../engine/prompt.js';
import { renderPage } from './site-template.mjs';

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const styleIds = arg('--style')?.split(',') ?? STYLE_IDS;
const LOCALES = arg('--locale')?.split(',') ?? ['en-US', 'de-DE', 'ja'];
const skipRender = process.argv.includes('--skip-render');
const SITE_BASE = process.env.SITE_BASE ?? '/site/'; // local server root is the repo
const SHOTS_URL = process.env.SHOTS_URL ?? `${SITE_BASE}shots/`;
const SITE_URL = process.env.SITE_URL ?? 'https://graphicmeat.com';
const THUMB_W = { mac: 960, iphone: 420, ipad: 560 };

export const DEMOS = [
  { app: 'mailvault', set: 'demo/mailvault/set.json', platforms: ['mac'] },
  { app: 'photobooks', set: 'demo/photobooks/set.json', platforms: ['iphone', 'ipad'] },
];

const sets = Object.fromEntries(await Promise.all(DEMOS.map(async d =>
  [d.app, JSON.parse(await readFile(join(ROOT, d.set), 'utf8'))])));

// One manifest entry per style and demo: the prompt shown on the page and the exact params rendered.
const manifest = [];
for (const id of styleIds) {
  const style = await loadStyle(id);
  for (const d of DEMOS) {
    const resolved = resolveSet({ ...sets[d.app], style: id }, {}, style.themes);
    const prompt = toPrompt({ style: id, theme: resolved.theme, accent: resolved.accent, platforms: d.platforms }, style.summary);
    manifest.push({ style: id, name: style.name, summary: style.summary, app: d.app, appName: sets[d.app].app.name,
      set: d.set, platforms: d.platforms, theme: resolved.theme, accent: resolved.accent, prompt,
      slots: sets[d.app].slots.map(s => s.id) });
  }
}

if (!skipRender) {
  const r = await startRenderer({ jobs: 6 });
  let done = 0;
  const total = manifest.reduce((n, m) => n + m.platforms.length * LOCALES.length * m.slots.length, 0);
  try {
    const tasks = [];
    for (const m of manifest) for (const platform of m.platforms) for (const locale of LOCALES) for (const [slot] of m.slots.entries()) {
      tasks.push((async () => {
        const res = await r.renderOne({ setPath: join(ROOT, m.set), platform, locale, slot, style: m.style, theme: m.theme, accent: m.accent });
        const file = join(ROOT, 'site/shots', m.style, m.app, platform, locale, `${String(slot + 1).padStart(2, '0')}.webp`);
        await mkdir(dirname(file), { recursive: true });
        await sharp(res.buffer).resize({ width: THUMB_W[platform] }).webp({ quality: 82 }).toFile(file);
        for (const w of res.warnings ?? []) console.warn(`WARN ${m.style} ${platform} ${locale} #${slot}: ${w}`);
        if (++done % 50 === 0) console.log(`${done}/${total}`);
      })());
    }
    const results = await Promise.allSettled(tasks);
    const failed = results.filter(x => x.status === 'rejected');
    for (const f of failed) console.error('FAIL', f.reason.message);
    if (failed.length) process.exitCode = 1;
  } finally {
    await r.close();
  }
}

// The skill's style list is generated, never hand-edited.
const styleRows = [...new Map(manifest.map(m => [m.style, m])).values()];
await writeFile(join(ROOT, 'skills/shot-butcher/references/styles.md'), `# Styles\n\nGenerated by scripts/build-gallery.mjs. Preview: npm run serve, then /site/.\n\n| id | name | themes | look |\n|---|---|---|---|\n` +
  (await Promise.all(styleRows.map(async m => `| ${m.style} | ${m.name} | ${(await loadStyle(m.style)).themes.join(', ')} | ${m.summary} |`))).join('\n') + '\n');
await writeFile(join(ROOT, 'site/gallery.json'), JSON.stringify(manifest, null, 2) + '\n');
for (const locale of LOCALES) {
  const path = locale === 'en-US' ? 'index.html' : `${locale}/index.html`;
  await mkdir(join(ROOT, 'site', dirname(path)), { recursive: true });
  await writeFile(join(ROOT, 'site', path), renderPage({ manifest, locale, locales: LOCALES, SITE_BASE, SHOTS_URL, SITE_URL, THUMB_W }));
}
await writeFile(join(ROOT, 'site/robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${SITE_URL}${SITE_BASE}sitemap.xml\n`);
await writeFile(join(ROOT, 'site/sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  LOCALES.map(l => `  <url><loc>${SITE_URL}${SITE_BASE}${l === 'en-US' ? '' : l + '/'}</loc></url>`).join('\n') + '\n</urlset>\n');
console.log(`site written: ${LOCALES.length} pages, ${manifest.length / DEMOS.length} styles`);
